#!/usr/bin/env python3
"""Rebuild the standalone, import-free EffectCraft Pixel Sorter WASM asset.

The result is embedded in a Python *source* module so the desktop/CLI converter
works offline without npm, a Rust compiler, PyInstaller data files or executing
any supplied Adobe binary. Requires AssemblyScript 0.28.20 to rebuild only:
    npm install --prefix .venv/wasm-tools --no-save assemblyscript@0.28.20
    python tools/build_pixel_sorter.py --asc .venv/wasm-tools/node_modules/.bin/asc
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import shutil
import subprocess
import tempfile
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'effectcraft_plugins/pixel_sorter_manifest.json'
TEMPLATE = ROOT / 'effectcraft_plugins/pixel_sorter.ts.in'
OUTPUT = ROOT / 'craft_converter/effectcraft_pixel_sorter.py'


def build(compiler: str, *, output: Path = OUTPUT) -> None:
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    if (manifest.get('api') != 1 or len(manifest.get('params', [])) != 18
            or len({p['id'] for p in manifest['params']}) != 18):
        raise ValueError('Unexpected EffectCraft plug-in manifest.')
    manifest_json = json.dumps(manifest, separators=(',', ':'), ensure_ascii=False)
    meta = manifest_json.encode('utf-8')
    if len(meta) >= 60_000:
        raise ValueError('Manifest would overlap the reserved host buffer.')
    template = TEMPLATE.read_text(encoding='utf-8')
    if template.count('__MANIFEST_BYTES__') != 1 or template.count('__MANIFEST_LEN__') != 1:
        raise ValueError('Missing/duplicate manifest placeholders in AssemblyScript source.')
    array = ',\n  '.join(', '.join(str(c) for c in meta[i:i+20])
                          for i in range(0, len(meta), 20))
    source = template.replace('__MANIFEST_BYTES__', array).replace('__MANIFEST_LEN__', str(len(meta)))
    with tempfile.TemporaryDirectory(prefix='effectcraft-wasm-') as folder:
        ts = Path(folder) / 'pixel_sorter.ts'
        wasm = Path(folder) / 'pixel_sorter.wasm'
        ts.write_text(source, encoding='utf-8')
        subprocess.run([compiler, str(ts), '-o', str(wasm), '--runtime', 'stub',
                        '--noAssert', '--optimize'], check=True)
        payload = wasm.read_bytes()
        if not payload.startswith(b'\0asm') or len(payload) > 512_000:
            raise ValueError('Compiler did not produce a small WASM module.')
        if shutil.which('node'):
            script = '''const fs=require('fs'),m=new WebAssembly.Module(fs.readFileSync(process.argv[1]));
if(WebAssembly.Module.imports(m).length)throw Error('EffectCraft forbids WASM imports');
let e=new WebAssembly.Instance(m,{}).exports;
if(e.ec_api_version()!==1)throw Error('wrong API version');
for(let n of ['memory','ec_manifest_ptr','ec_manifest_len','ec_alloc','ec_render'])
if(!e[n])throw Error('missing '+n);
let text=Buffer.from(e.memory.buffer,e.ec_manifest_ptr(),e.ec_manifest_len()).toString('utf8');
if(text!==process.argv[2])throw Error('manifest mismatch');'''
            subprocess.run(['node', '-e', script, str(wasm), manifest_json], check=True)
    encoded = base64.b64encode(payload).decode('ascii')
    lines = '\n'.join(f'    {line!r}' for line in textwrap.wrap(encoded, 100))
    body = ('"""Self-contained, independently written EffectCraft Pixel Sorter plug-in.\n\n'
            'Generated by tools/build_pixel_sorter.py from the independent\n'
            'AssemblyScript source in effectcraft_plugins/pixel_sorter.ts.in.\n'
            'This module does not contain or execute Adobe plug-in code.\n'
            '"""\n'
            'import base64\n'
            'import json\n\n'
            f'MANIFEST = json.loads({manifest_json!r})\n'
            f'MANIFEST_SHA256 = {hashlib.sha256(meta).hexdigest()!r}\n'
            f'WASM_SHA256 = {hashlib.sha256(payload).hexdigest()!r}\n'
            'WASM = base64.b64decode(\n'
            f'{lines}\n'
            ')\n')
    output.write_text(body, encoding='utf-8')
    print(f'Generated {output} ({len(payload)} WASM bytes; sha256={hashlib.sha256(payload).hexdigest()})')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--asc', default=shutil.which('asc'),
                        help='AssemblyScript compiler; install assemblyscript@0.28.20 to rebuild')
    args = parser.parse_args()
    if not args.asc:
        parser.error('AssemblyScript asc not found; pass --asc or install it with npm')
    build(args.asc)


if __name__ == '__main__':
    main()
